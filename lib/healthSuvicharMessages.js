function getISTDateKey(date = new Date()) {
	const parts = new Intl.DateTimeFormat('en-CA', {
		timeZone: 'Asia/Kolkata',
		year: 'numeric',
		month: '2-digit',
		day: '2-digit',
	}).formatToParts(date);

	const year = parts.find((part) => part.type === 'year')?.value;
	const month = parts.find((part) => part.type === 'month')?.value;
	const day = parts.find((part) => part.type === 'day')?.value;

	return `${year}-${month}-${day}`;
}

function hashDateKey(dateKey) {
	let hash = 0;
	for (let i = 0; i < dateKey.length; i += 1) {
		hash = (hash * 31 + dateKey.charCodeAt(i)) >>> 0;
	}
	return hash;
}

export function getDailyHealthSuvichar(date = new Date()) {
	if (!HEALTH_SUVICHAR_MESSAGES.length) {
		return 'स्वास्थ्य का ध्यान रखें, स्वस्थ जीवन जिएं।';
	}

	const dateKey = getISTDateKey(date);
	const index = hashDateKey(dateKey) % HEALTH_SUVICHAR_MESSAGES.length;
	return HEALTH_SUVICHAR_MESSAGES[index];
}
